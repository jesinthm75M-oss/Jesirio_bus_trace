// Helper to interpolate dense waypoints between stops for fluid GPS movements
function createWaypoints(stops: BusStop[]): [number, number][] {
  const result: [number, number][] = [];
  for (let i = 0; i < stops.length - 1; i++) {
    const p1 = stops[i];
    const p2 = stops[i + 1];
    const steps = 14; // intermediate waypoints
    for (let s = 0; s <= steps; s++) {
      const t = s / steps;
      // Slight natural road curvature
      const jitterLat = Math.sin(t * Math.PI) * 0.0012 * (i % 2 === 0 ? 1 : -1);
      const jitterLng = Math.cos(t * Math.PI) * 0.0014 * (i % 2 === 0 ? -1 : 1);
      const lat = p1.lat + (p2.lat - p1.lat) * t + jitterLat;
      const lng = p1.lng + (p2.lng - p1.lng) * t + jitterLng;
      result.push([Number(lat.toFixed(6)), Number(lng.toFixed(6))]);
    }
  }
  return result;
}

